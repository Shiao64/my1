/* Rebuild the Asia first-load bundles. Sources stay editable; the pages load the outputs.
   node tools/build_asia_assets.mjs
*/
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
function run(args, input) {
  const r = spawnSync('npx', ['--yes', 'esbuild', ...args], { input, cwd: root, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 });
  if (r.status !== 0) {
    process.stderr.write(r.stderr || r.stdout || 'esbuild failed\n');
    process.exit(r.status || 1);
  }
  return r.stdout;
}

function bundle(files, outfile, banner) {
  const src = files.map((f) => readFileSync(join(root, f), 'utf8')).join('\n');
  const out = run(['--minify', '--target=es2018'], src);
  writeFileSync(join(root, outfile), banner + out);
}

mkdirSync(join(root, 'asia'), { recursive: true });

bundle(
  ['asia/lang-pref.js', 'asia/atm-nav.js'],
  'asia/atm-early.js',
  '/* generated by tools/build_asia_assets.mjs from lang-pref.js + atm-nav.js */\n'
);

bundle(
  ['asia/asia-reglist.js', 'asia/asia-fav.js', 'asia/atm-menu.js', 'asia/lang-keep.js', 'asia/atm-push.js'],
  'asia/atm-later.js',
  '/* generated by tools/build_asia_assets.mjs from asia-reglist, asia-fav, atm-menu, lang-keep, atm-push */\n'
);

const cssSrc = join(root, 'asia/.atm-critical.src.css');
const cssOut = join(root, 'asia/atm-critical.css');
writeFileSync(cssSrc, ['css/atm-map-page.css', 'css/style.css', 'asia/cardB.css'].map((f) => readFileSync(join(root, f), 'utf8')).join('\n'));
const cssRun = spawnSync('npx', ['--yes', 'esbuild', cssSrc, '--minify', `--outfile=${cssOut}`], { cwd: root, encoding: 'utf8' });
if (cssRun.status !== 0) {
  process.stderr.write(cssRun.stderr || cssRun.stdout || 'css minify failed\n');
  process.exit(cssRun.status || 1);
}
const minCss = readFileSync(cssOut, 'utf8');
writeFileSync(cssOut, '/* generated by tools/build_asia_assets.mjs from atm-map-page.css + style.css + cardB.css */\n' + minCss);
spawnSync('rm', ['-f', cssSrc]);
